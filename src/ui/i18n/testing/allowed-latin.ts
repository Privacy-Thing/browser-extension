/** Removes any of `characters` from the end of `text`. */
export const trimTrailing = (text: string, characters: string) => {
  let end = text.length;
  while (end > 0 && characters.includes(text.charAt(end - 1))) end -= 1;
  return text.slice(0, end);
};

