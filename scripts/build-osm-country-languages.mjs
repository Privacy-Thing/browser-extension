import fs from "node:fs";
import process from "node:process";
import { URL } from "node:url";

const OSM_COUNTRY_SOURCE_URL =
  "https://wiki.openstreetmap.org/w/index.php?title=Nominatim/Country_Codes&action=raw";

const extractTableRows = (source) => {
  const tableStart = source.indexOf('{|class="wikitable sortable"');
  const tableEnd = source.indexOf("\n|}", tableStart);

  if (tableStart === -1 || tableEnd === -1) {
    throw new Error(
      "Could not locate the OSM country language table in the source page.",
    );
  }

  const tableSource = source.slice(tableStart, tableEnd);
  return tableSource
    .split("\n|-")
    .slice(2)
    .map((row) => row.trim())
    .filter((row) => row.length > 0);
};

const parseCountryLanguageRow = (row) => {
  const lines = row
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.length > 0);
  const countryCodeLine = lines.find((line) =>
    line.startsWith('|style="text-align:center"|'),
  );
  const languageCodeLine = lines.at(-1);

  if (!countryCodeLine || !languageCodeLine) {
    return null;
  }

  const countryCodeMatch = countryCodeLine.match(/<tt>([A-Z]{2})<\/tt>/);
  if (!countryCodeMatch) {
    return null;
  }

  const languageCodes = [...languageCodeLine.matchAll(/>([A-Za-z0-9-]+)<\/tt>/g)].map(
    (match) => match[1],
  );

  if (languageCodes.length === 0) {
    return null;
  }

  return {
    countryCode: countryCodeMatch[1].toLowerCase(),
    languageCodes,
  };
};

const buildOutput = (
  entries,
) => `// Generated by scripts/build-osm-country-languages.mjs. Do not edit by hand.
// Source catalog:
// - OpenStreetMap Wiki: ${OSM_COUNTRY_SOURCE_URL}

export type OsmCountryLanguageEntry = {
  readonly countryCode: string;
  readonly languageCodes: readonly string[];
};

export const osmCountryLanguageCatalog = ${JSON.stringify(entries, null, 2)} as const satisfies readonly OsmCountryLanguageEntry[];

export const osmCountryLanguageMap = Object.freeze(
  Object.fromEntries(
    osmCountryLanguageCatalog.map((entry) => [entry.countryCode, entry.languageCodes])
  )
) as Readonly<Record<string, readonly string[]>>;
`;

const response = await globalThis.fetch(OSM_COUNTRY_SOURCE_URL, {
  headers: {
    Accept: "text/plain",
  },
});

if (!response.ok) {
  throw new Error(
    `Could not download OSM country language source (${response.status}).`,
  );
}

const source = await response.text();
const entries = extractTableRows(source)
  .map(parseCountryLanguageRow)
  .filter((entry) => entry !== null)
  .sort((left, right) => left.countryCode.localeCompare(right.countryCode, "en"));

// Refuse to emit a structurally-valid-but-broken catalog: all-malformed rows
// would collapse to an empty/tiny list, and duplicate country codes would
// silently clobber entries in the derived map.
const MIN_OSM_COUNTRIES = 100;
if (entries.length < MIN_OSM_COUNTRIES) {
  throw new Error(
    `osm: only ${entries.length} countries (< ${MIN_OSM_COUNTRIES}) — refusing to write a broken catalog`,
  );
}
const seenCountryCodes = new Set();
for (const entry of entries) {
  if (seenCountryCodes.has(entry.countryCode)) {
    throw new Error(
      `osm: duplicate country code "${entry.countryCode}" — refusing to write a broken catalog`,
    );
  }
  seenCountryCodes.add(entry.countryCode);
}

const osmOutputPath = new URL(
  "../src/shared/osm-country-languages.generated.ts",
  import.meta.url,
);
const osmTmpPath = new URL(`${osmOutputPath.href}.tmp`);
fs.writeFileSync(osmTmpPath, buildOutput(entries));
fs.renameSync(osmTmpPath, osmOutputPath);

process.stdout.write(`Generated ${entries.length} OSM country language entries\n`);
