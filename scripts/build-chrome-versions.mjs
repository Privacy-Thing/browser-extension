import fs from "node:fs";
import process from "node:process";
import { URL } from "node:url";

const CHROMIUMDASH_BASE_URL =
  "https://chromiumdash.appspot.com/fetch_releases?num=700&offset=0&platform=";

const OUTPUT_PATH = new URL(
  "../src/shared/chrome-versions.generated.ts",
  import.meta.url,
);
const MAX_AGE_MS = 24 * 60 * 60 * 1000; // 24 hours

const isOutputFresh = () => {
  try {
    const { mtimeMs } = fs.statSync(OUTPUT_PATH);
    return Date.now() - mtimeMs < MAX_AGE_MS;
  } catch {
    return false;
  }
};

const FORCE_REGEN =
  process.env.PT_FORCE_REGEN === "1" || process.argv.includes("--force");

if (!FORCE_REGEN && isOutputFresh()) {
  process.stdout.write(
    "chrome-versions.generated.ts is less than 24h old — skipping download.\n",
  );
  process.exit(0);
}

const PLATFORMS = [
  { apiName: "Windows", catalogKey: "windows" },
  { apiName: "Mac", catalogKey: "mac" },
  { apiName: "Linux", catalogKey: "linux" },
];

const fetchVersionsForPlatform = async (apiName) => {
  const url = `${CHROMIUMDASH_BASE_URL}${apiName}`;
  const response = await globalThis.fetch(url, {
    headers: { Accept: "application/json" },
  });

  if (!response.ok) {
    throw new Error(
      `Could not download Chrome version list for ${apiName} (${response.status}).`,
    );
  }

  const releases = await response.json();
  if (!Array.isArray(releases)) {
    throw new Error(`Unexpected response shape for ${apiName}: expected array.`);
  }

  const stableMilestone = releases.find((r) => r.channel === "Stable")?.milestone;
  const minMilestone =
    typeof stableMilestone === "number" ? stableMilestone - 15 : undefined;

  if (minMilestone !== undefined) {
    process.stdout.write(
      `  Stable milestone: ${stableMilestone} — keeping major >= ${minMilestone}\n`,
    );
  }

  return releases
    .filter(
      (release) =>
        minMilestone === undefined || (release.milestone ?? 0) >= minMilestone,
    )
    .map((release) => release.version)
    .filter(
      (version) => typeof version === "string" && /^\d+\.\d+\.\d+\.\d+$/.test(version),
    );
};

const groupByMajor = (versions) => {
  const byMajor = {};

  for (const version of versions) {
    const major = version.split(".")[0];
    if (!major) continue;
    if (!byMajor[major]) {
      byMajor[major] = [];
    }
    if (!byMajor[major].includes(version)) {
      byMajor[major].push(version);
    }
  }

  for (const major of Object.keys(byMajor)) {
    byMajor[major].sort((a, b) => {
      const [, , buildA = "0", patchA = "0"] = a.split(".");
      const [, , buildB = "0", patchB = "0"] = b.split(".");
      const buildDiff = Number(buildB) - Number(buildA);
      return buildDiff !== 0 ? buildDiff : Number(patchB) - Number(patchA);
    });
  }

  return byMajor;
};

const buildOutput = (
  catalog,
) => `// Generated by scripts/build-chrome-versions.mjs. Do not edit by hand.
// Sources:
${PLATFORMS.map((p) => `// - Chromiumdash ${p.apiName}: ${CHROMIUMDASH_BASE_URL}${p.apiName}`).join("\n")}

export type ChromeVersionPlatformKey = "windows" | "mac" | "linux";

export type ChromeVersionsByMajor = Readonly<Record<string, readonly string[]>>;

export type ChromeVersionCatalog = Readonly<Record<ChromeVersionPlatformKey, ChromeVersionsByMajor>>;

export const chromeVersionCatalog = ${JSON.stringify(catalog, null, 2)} as const satisfies ChromeVersionCatalog;
`;

const catalog = { windows: {}, mac: {}, linux: {} };
let totalVersions = 0;

for (const { apiName, catalogKey } of PLATFORMS) {
  process.stdout.write(`Fetching ${apiName}...\n`);
  const versions = await fetchVersionsForPlatform(apiName);
  catalog[catalogKey] = groupByMajor(versions);
  const count = versions.length;
  totalVersions += count;
  process.stdout.write(
    `  ${count} versions across ${Object.keys(catalog[catalogKey]).length} major versions\n`,
  );
}

// Refuse to emit a structurally-valid-but-broken catalog: a missing "Stable"
// milestone or fully-filtered upstream would otherwise produce empty per-platform
// maps ({ windows: {}, ... }) that ship a useless version catalog.
for (const { catalogKey } of PLATFORMS) {
  const byMajor = catalog[catalogKey];
  const majors = Object.keys(byMajor);
  if (majors.length === 0) {
    throw new Error(
      `chrome: platform "${catalogKey}" has no versions — refusing to write a broken catalog`,
    );
  }
  for (const major of majors) {
    if (!Array.isArray(byMajor[major]) || byMajor[major].length === 0) {
      throw new Error(
        `chrome: ${catalogKey}.${major} has no versions — refusing to write a broken catalog`,
      );
    }
  }
}

const chromeTmpPath = new URL(`${OUTPUT_PATH.href}.tmp`);
fs.writeFileSync(chromeTmpPath, buildOutput(catalog));
fs.renameSync(chromeTmpPath, OUTPUT_PATH);

process.stdout.write(
  `Generated Chrome version catalog with ${totalVersions} total versions\n`,
);
