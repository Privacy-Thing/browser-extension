// Generates the character sets the Chinese catalog tests use to keep Simplified and
// Traditional copy apart. The data comes from OpenCC (Apache-2.0), pinned to one
// commit so the output only changes when this script changes.
import fs from "node:fs";
import process from "node:process";
import { URL } from "node:url";

import { fetchTrustedText } from "./upstream-fetch.mjs";

const OPENCC_COMMIT = "a806b775d038f9fa7c061f50d270115e7ad7da5b";
const OPENCC_ORIGIN = "https://raw.githubusercontent.com";
const OUTPUT_PATH = new URL(
  "../src/ui/i18n/glossary/zh-script-charsets.generated.ts",
  import.meta.url,
);

const dictionaryUrl = (name) =>
  `${OPENCC_ORIGIN}/BYVoid/OpenCC/${OPENCC_COMMIT}/data/dictionary/${name}.txt`;

const readDictionary = async (name) => {
  const text = await fetchTrustedText({
    url: dictionaryUrl(name),
    allowedOrigins: [OPENCC_ORIGIN],
    acceptedContentTypes: ["text/plain"],
    accept: "text/plain",
  });
  const entries = new Map();
  for (const line of text.split("\n")) {
    if (line.startsWith("#") || line.trim() === "") continue;
    const [key, values] = line.split("\t");
    if (!key || !values || [...key].length !== 1) continue;
    entries.set(key, values.trim().split(" "));
  }
  if (entries.size === 0) throw new Error(`OpenCC ${name} has no entries`);
  return entries;
};

/** Keys whose mappings never keep the character itself: they exist in one form only. */
const exclusiveKeys = (dictionary) =>
  [...dictionary]
    .filter(([key, values]) => !values.includes(key))
    .map(([key]) => key)
    .sort((left, right) => left.codePointAt(0) - right.codePointAt(0))
    .join("");

const [simplifiedToTraditional, traditionalToSimplified, taiwanVariants] =
  await Promise.all(
    ["STCharacters", "TSCharacters", "TWVariants"].map((name) => readDictionary(name)),
  );

const output = `// Generated by scripts/generate-zh-script-charsets.mjs. Do not edit by hand.
// Source: OpenCC (https://github.com/BYVoid/OpenCC), commit ${OPENCC_COMMIT},
// data/dictionary/{STCharacters,TSCharacters,TWVariants}.txt.
// OpenCC is licensed under the Apache License 2.0 (licenses/Apache-2.0.txt).
// Used only by tests; not bundled into the extension.

/** Characters that exist only in Traditional Chinese (TSCharacters keys). */
export const TRADITIONAL_ONLY_CHARACTERS =
  ${JSON.stringify(exclusiveKeys(traditionalToSimplified))};

/** Characters that exist only in Simplified Chinese (STCharacters keys). */
export const SIMPLIFIED_ONLY_CHARACTERS =
  ${JSON.stringify(exclusiveKeys(simplifiedToTraditional))};

/** Traditional variants that Taiwan writes differently, such as 爲 for 為 (TWVariants keys). */
export const NON_TAIWAN_VARIANT_CHARACTERS = ${JSON.stringify(exclusiveKeys(taiwanVariants))};
`;

fs.writeFileSync(OUTPUT_PATH, output);
process.stdout.write(`Wrote ${OUTPUT_PATH.pathname}\n`);
